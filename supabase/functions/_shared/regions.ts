/**
 * 날씨 지역 (SPEC.md 3.6, 7.1). 위치 권한 대신 사용자가 시·도와 시·군·구를 고른다.
 *
 * 특별시·광역시는 구·군까지, 나머지 도는 시·군까지 나눈다. 일반 시의 구끼리는 5km 격자 예보가 사실상 같다.
 * 좌표는 시청·군청·구청 근처로, 격자 한 칸(5km) 안쪽이면 된다. 옹진군은 섬 주민이 많은 영흥도로 잡았다.
 *
 * id 는 "시·도 이름 + 지역 이름"이다. 앱 설정에 저장되는 값이라 바꾸지 않는다.
 * 앱에 같은 목록이 있고(apps/mobile/src/weather/regions.ts) 둘이 어긋나지 않게 앱 테스트가 지킨다.
 */

