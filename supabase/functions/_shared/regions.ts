export type AirArea = (typeof AIR_AREAS)[number];

export interface Region {
  id: string;
  /** 시·도 */
  sido: string;
  /** 시·군·구 */
  name: string;
  lat: number;
  lon: number;
  air: AirArea;
}

type Row = [name: string, lat: number, lon: number, air?: AirArea];

function group(sido: string, air: AirArea, rows: Row[]): Region[] {
  return rows.map(([name, lat, lon, area]) => ({
    id: `${sido} ${name}`,
    sido,
    name,
    lat,
    lon,
    air: area ?? air,
  }));
}

